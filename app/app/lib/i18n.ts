export type AppCopy = (typeof COPY)[LanguageCode];

export function copyFor(language: LanguageCode): AppCopy {
  return COPY[language] as AppCopy;
}

export function statusLabel(language: LanguageCode, status: AttendanceStatus) {
  const copy = copyFor(language);
  const labels: Record<AttendanceStatus, string> = {
    PRESENT: copy.present,
    HALF_DAY: copy.halfDay,
    ABSENT: copy.absent,
    WEEKLY_OFF: copy.weeklyOff,
    HOLIDAY: copy.holiday,
    LEAVE: copy.leave,
  };
  return labels[status];
}
